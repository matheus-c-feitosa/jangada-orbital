export type Key = keyof typeof D
/** every string, [English, Portuguese], for the tests */
export const DICTIONARY: Record<Key, readonly [string, string]> = D
type Vars = Record<string, string | number>

const fill = (s: string, v?: Vars) => (v ? s.replace(/\{(\w+)\}/g, (_, k: string) => (k in v ? String(v[k]) : `{${k}}`)) : s)

const MONTHS = {
  en: { long: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'], short: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'] },
  pt: { long: ['janeiro', 'fevereiro', 'março', 'abril', 'maio', 'junho', 'julho', 'agosto', 'setembro', 'outubro', 'novembro', 'dezembro'], short: ['Jan', 'Fev', 'Mar', 'Abr', 'Mai', 'Jun', 'Jul', 'Ago', 'Set', 'Out', 'Nov', 'Dez'] },
}

// One set of formatters per language: every component asks for them, and Intl formatters are slow to build.
const made: Partial<Record<Lang, ReturnType<typeof build>>> = {}
export function makeI18n(lang: Lang) {
  return (made[lang] ??= build(lang))
}

function build(lang: Lang) {
  const i = lang === 'pt' ? 1 : 0
  const locale = lang === 'pt' ? 'pt-BR' : 'en-US'
  const int = new Intl.NumberFormat(locale, { maximumFractionDigits: 0 })
  const one = new Intl.NumberFormat(locale, { minimumFractionDigits: 1, maximumFractionDigits: 1 })
  const upTo1 = new Intl.NumberFormat(locale, { maximumFractionDigits: 1 })
  const pct = new Intl.NumberFormat(locale, { style: 'percent', maximumFractionDigits: 1 })
  const compact = new Intl.NumberFormat(locale, { notation: 'compact', maximumFractionDigits: 1 })
  const m = MONTHS[lang]
  return {
    lang,
    locale,
    t: (key: Key, vars?: Vars) => fill(D[key][i], vars),
    int: (v: number) => int.format(Math.round(v)),
    /** "1 detection" / "14 detections", rounded as shown */
    det: (v: number) => (Math.round(v) === 1 ? D.nDetection1[i] : fill(D.nDetections[i], { n: int.format(Math.round(v)) })),
    one: (v: number) => one.format(v),
    upTo1: (v: number) => upTo1.format(v),
    pct: (v: number) => pct.format(v),
    compact: (v: number) => compact.format(v),
    /** "14.1k" / "14,1 mil": the short counts of the design */
    k: (v: number) => {
      if (v < 1000) return int.format(Math.round(v))
      if (lang === 'en') return `${(v / 1000).toFixed(v >= 100_000 ? 0 : 1)}k`
      return `${v >= 100_000 ? int.format(v / 1000) : one.format(v / 1000).replace(/,0$/, '')} mil`
    },
    /** "34th" in English; "34" in Portuguese, where the sentence says "percentil 34" */
    ord: (n: number) => {
      if (lang === 'pt') return String(n)
      const s = ['th', 'st', 'nd', 'rd'], v = n % 100
      return n + (s[(v - 20) % 10] || s[v] || s[0])
    },
    monthLong: (k: number) => m.long[k],
    monthShort: (k: number) => m.short[k],
    /** "14 Nov 2026" / "14 nov 2026" from "2026-11-14"; without the year, for sentences: "14 Nov" / "14 de novembro" */
    day: (iso: string, withYear = true) => {
      const d = Number(iso.slice(8, 10)), k = Number(iso.slice(5, 7)) - 1
      if (lang === 'pt') return withYear ? `${d} ${m.short[k].toLowerCase()} ${iso.slice(0, 4)}` : `${d} de ${m.long[k]}`
      return `${d} ${m.short[k]}${withYear ? ` ${iso.slice(0, 4)}` : ''}`
    },
  }
}

export type I18n = ReturnType<typeof makeI18n>

export const LangContext = createContext<Lang>('en')
export function useI18n(): I18n {
  return makeI18n(useContext(LangContext))
}

const LANG_KEY = 'jangada-lang'
export function initialLang(): Lang {
  const q = new URLSearchParams(window.location.search).get('lang')
  if (q === 'pt' || q === 'en') return q
  try {
    if (localStorage.getItem(LANG_KEY) === 'pt') return 'pt'
  } catch { /* storage blocked: English */ }
  return 'en'
}
export function saveLang(lang: Lang) {
  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en'
  try { localStorage.setItem(LANG_KEY, lang) } catch { /* not persisted; still applied */ }
}
